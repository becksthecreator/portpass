-- Brief 31 (C), 11 Oct 2026: each coach's own inbox, days and pay.
--
-- 1. What Futprep pays a coach for a private session, set by the CEO or an
--    admin on the operating map: one rate for 30 minutes, one for 60.
--    Futprep enters them; nothing in code sets a pay rate. Null = not set.
-- 2. Where a private session happens: one of Futprep's places that takes
--    private sessions (locations.private_sessions_ok, 202610210003), or a
--    place the parent suggests (location_preference, kept as it was).
-- 3. private_session_pay: one line per completed private session, for the
--    coach who took it, at their rate for its length. A record of what
--    Futprep owes and has paid; PortPass never holds or moves the money.
--    Owner-only, like session_staff: no browser role reads or writes it.
--
-- Switch back:
--   drop table public.private_session_pay;
--   alter table public.private_session_requests drop column location_id, drop column time_to_confirm;
--   alter table public.coach_profiles drop column private_30_pay_cents, drop column private_60_pay_cents;

alter table public.coach_profiles add column if not exists private_30_pay_cents integer;
alter table public.coach_profiles add column if not exists private_60_pay_cents integer;
alter table public.coach_profiles drop constraint if exists coach_profiles_private_pay_check;
alter table public.coach_profiles add constraint coach_profiles_private_pay_check
  check ((private_30_pay_cents is null or private_30_pay_cents between 0 and 10000000)
     and (private_60_pay_cents is null or private_60_pay_cents between 0 and 10000000));

alter table public.private_session_requests
  add column if not exists location_id bigint references public.locations(id) on delete set null;
-- The preferred coach had no working days when the parent asked: the coach
-- will confirm a time, and the request is flagged in the admin inbox too.
alter table public.private_session_requests
  add column if not exists time_to_confirm boolean not null default false;

create index if not exists private_session_requests_preferred_coach_idx on public.private_session_requests(preferred_coach_id);
create index if not exists private_session_requests_assigned_coach_idx on public.private_session_requests(assigned_coach_id);

create table if not exists public.private_session_pay (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations(id) on delete cascade,
  request_id bigint not null unique references public.private_session_requests(id),
  coach_id bigint not null references public.coach_profiles(id),
  duration_minutes integer not null check (duration_minutes between 15 and 480),
  pay_cents integer not null default 0 check (pay_cents between 0 and 10000000),
  -- How the amount was worked out (lib/coachPay.ts privatePayFor): the
  -- coach's 30- or 60-minute rate, pro rata from one of them for another
  -- length, or not_set ($0 until Futprep sets a rate).
  rate_basis text not null default 'not_set' check (rate_basis in ('rate_30', 'rate_60', 'pro_rata_60', 'pro_rata_30', 'not_set')),
  paid_at timestamptz,
  paid_by text,
  created_by text,
  created_at timestamptz not null default now()
);

create index if not exists private_session_pay_coach_idx on public.private_session_pay(coach_id, paid_at);


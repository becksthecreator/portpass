-- Brief 31 (D), 11 Oct 2026: the Progress Passport. A coach scores each
-- child at the start and end of a term, writes a short note, and Futprep
-- shares it with the family, who see it on /futprep/my/[code].
--
-- 1. passport_skills: what is scored. organization_id null is the default
--    set every business starts from: five football skills, and five for
--    Lil Kickers under 4. A business can add its own rows later.
-- 2. passports: one per child per term (a registration is one child in
--    one program and term) or, later, one per private-session request;
--    exactly one of the two. draft until shared, then shared for good.
-- 3. passport_marks: one row per passport and skill, a start and an end
--    score from 1 to 5. Each tap on the roster saves one row.
-- 4. passport_notes: one per passport: a note of up to 500 characters, a
--    link to a clip (https only, and only when the registration's photo
--    permission is yes, checked here by a trigger as well as in the app),
--    and a suggested next class or session (an offering).
--
-- Children's health details are never stored or shown here. Everything
-- goes when its registration, request or offering is deleted (the demo
-- reset depends on that). Owner-only, like the rest of a child's record:
-- no browser role reads or writes any of it.
--
-- Switch back:
--   drop table public.passport_notes, public.passport_marks, public.passports, public.passport_skills;
--   drop function public.passport_clip_needs_photo_permission();

create table if not exists public.passport_skills (
  id bigint generated by default as identity primary key,
  organization_id bigint references public.organizations(id) on delete cascade,
  band text not null check (band in ('football', 'lil_kickers')),
  name text not null check (length(name) between 1 and 60),
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create unique index if not exists passport_skills_default_name on public.passport_skills(band, name) where organization_id is null;
create unique index if not exists passport_skills_org_name on public.passport_skills(organization_id, band, name) where organization_id is not null;


create table if not exists public.passports (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations(id) on delete cascade,
  registration_id bigint references public.registrations(id) on delete cascade,
  private_session_request_id bigint references public.private_session_requests(id) on delete cascade,
  band text not null check (band in ('football', 'lil_kickers')),
  status text not null default 'draft' check (status in ('draft', 'shared')),
  shared_at timestamptz,
  shared_by text,
  created_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint passports_one_subject check ((registration_id is null) <> (private_session_request_id is null))
);

create unique index if not exists passports_registration_key on public.passports(registration_id) where registration_id is not null;
create unique index if not exists passports_request_key on public.passports(private_session_request_id) where private_session_request_id is not null;
create index if not exists passports_org_status_idx on public.passports(organization_id, status);

create table if not exists public.passport_marks (
  id bigint generated by default as identity primary key,
  passport_id bigint not null references public.passports(id) on delete cascade,
  skill_id bigint not null references public.passport_skills(id) on delete cascade,
  start_score smallint check (start_score between 1 and 5),
  end_score smallint check (end_score between 1 and 5),
  updated_by text,
  updated_at timestamptz not null default now(),
  unique (passport_id, skill_id)
);

create table if not exists public.passport_notes (
  passport_id bigint primary key references public.passports(id) on delete cascade,
  note text not null default '' check (length(note) <= 500),
  clip_url text check (clip_url is null or (length(clip_url) <= 2048 and clip_url like 'https://%')),
  next_step_offering_id bigint references public.offerings(id) on delete set null,
  updated_by text,
  updated_at timestamptz not null default now()
);

-- A clip only for a child whose family said yes to photos and videos.
create or replace function public.passport_clip_needs_photo_permission()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if new.clip_url is not null and not exists (
    select 1
      from public.passports p
      join public.registrations r on r.id = p.registration_id
     where p.id = new.passport_id
       and r.photo_consent = 'yes'
  ) then
    raise exception 'CLIP_NOT_ALLOWED' using errcode = 'P0001';
  end if;
  return new;
end;
$$;

drop trigger if exists passport_notes_clip_permission on public.passport_notes;
create trigger passport_notes_clip_permission
  before insert or update on public.passport_notes
  for each row execute function public.passport_clip_needs_photo_permission();

revoke all on function public.passport_clip_needs_photo_permission() from public, anon, authenticated;

do $$
declare
  t text;
begin
  foreach t in array array['passport_skills', 'passports', 'passport_marks', 'passport_notes'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('drop policy if exists %I on public.%I', t || '_browser_roles_denied', t);
    execute format(
      'create policy %I on public.%I as restrictive for all to anon, authenticated using (false) with check (false)',
      t || '_browser_roles_denied', t
    );
  end loop;
end $$;
